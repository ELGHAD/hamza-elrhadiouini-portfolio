// Writes src/environments/build-info.ts (ignored by Git) with the build date shown in the footer.
// Fixed at build time so prerendered HTML and the browser show the same value.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const outputPath = resolve('src/environments/build-info.ts');
const buildDate = new Date().toISOString().slice(0, 10);

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/write-build-info.mjs. Do not commit.\nexport const BUILD_INFO = { date: '${buildDate}' } as const;\n`,
  'utf8',
);
