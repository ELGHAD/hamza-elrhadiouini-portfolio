// Generates src/environments/environment.ts (ignored by Git) from EMAILJS_* environment variables.
//   --require     fail unless all three variables are set (deployment).
//   --if-missing  keep an existing file untouched (npm start/build hooks on a fresh clone).
// With no variables, the form falls back to a mailto: link instead of sending.
import { access, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const outputPath = resolve('src/environments/environment.ts');

if (process.argv.includes('--if-missing')) {
  try {
    await access(outputPath);
    process.exit(0);
  } catch {
    // File absent: generate it below.
  }
}

const variables = {
  serviceId: process.env.EMAILJS_SERVICE_ID?.trim() ?? '',
  templateId: process.env.EMAILJS_TEMPLATE_ID?.trim() ?? '',
  publicKey: process.env.EMAILJS_PUBLIC_KEY?.trim() ?? '',
};
const configured = Object.values(variables).filter(Boolean).length;

if (configured > 0 && configured < Object.keys(variables).length) {
  throw new Error('Provide all three EmailJS variables or leave all three empty.');
}

if (process.argv.includes('--require') && configured !== Object.keys(variables).length) {
  throw new Error(
    'EMAILJS_SERVICE_ID, EMAILJS_TEMPLATE_ID and EMAILJS_PUBLIC_KEY must be set in GitHub Actions for deployment.',
  );
}

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/write-emailjs-env.mjs. Do not commit.\nexport const environment = ${JSON.stringify({ emailjs: variables }, null, 2)} as const;\n`,
  'utf8',
);
console.log(
  configured
    ? 'EmailJS environment written (form sends through EmailJS).'
    : 'EmailJS environment written without credentials (form falls back to mailto:).',
);
